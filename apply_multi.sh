#!/bin/bash
# Эксперимент «все резюме на каждую вакансию» (12.10.2026, крон хоста вместо apply3.sh).
#
# Отклики идут ВОЛНАМИ по 3 резюме (решение Александра 13.10: все 10, но не подряд): запуск
# `apply_multi.sh <волна>` с волной 0, 1, 2 — по крону 09:00, 13:00, 17:00 МСК.
# 1. Волна 0: основное резюме (HH_RESUME_ID) откликается на свежие вакансии — как apply3.sh.
# 2. Каждая волна: своя тройка из HH_EXTRA_RESUME_IDS переоткликается на вакансии, где аккаунт откликнулся
#    за последние 30 дней, ответа ещё нет (state=response) и этим резюме отклика нет. Работодатель видит
#    отклики тремя волнами с перерывом в несколько часов, а не 10 подряд (13.10: HR Алабуги заметила
#    3 отклика подряд и закрыла все шаблоном). Отказы и собеседования повторными откликами не заваливаем.
# Состав троек сдвигается по дню года, чтобы ни одно резюме не было всегда в первой волне.
# На «Лимит откликов hh.ru исчерпан» запуск останавливается — следующая волна/день добирает.
set -uo pipefail
cd /opt/hh-applicant-tool
set -a; . ./apply.env; set +a

run() {
  local out
  out=$(bash apply3.sh "$@" 2>&1); echo "$out"
  grep -q "Лимит откликов hh.ru исчерпан" <<<"$out" && { echo "⛔ лимит — цепочка остановлена"; exit 0; }
  return 0
}

WAVE=${1:-0}
WAVE_SIZE=3

if [ "$WAVE" -eq 0 ]; then
  echo "=== $(date '+%F %T') волна 0: основное резюме"
  run
fi

read -ra IDS <<<"${HH_EXTRA_RESUME_IDS:-}"
n=${#IDS[@]}
[ "$n" -eq 0 ] && exit 0
shift_by=$(( 10#$(date +%j) * WAVE_SIZE % n ))
for ((i = 0; i < WAVE_SIZE; i++)); do
  k=$(( WAVE * WAVE_SIZE + i ))
  [ "$k" -ge "$n" ] && break
  rid=${IDS[$(( (shift_by + k) % n ))]}
  echo "=== $(date '+%F %T') волна $WAVE: переотклик резюме ${rid:0:8}"
  RESUME_ID="$rid" run --reapply-rejected --reapply-states response --reapply-since-days 30
done
